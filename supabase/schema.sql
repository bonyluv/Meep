-- Ejecuta este archivo en Supabase: SQL Editor → New query → Run.
-- Las cuentas y contraseñas las gestiona Supabase Auth; aquí se guardan las mediciones.
create table if not exists public.mediciones (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_id text not null,
  food text not null,
  ph numeric,
  ts timestamptz not null,
  estado text not null check (estado in ('in', 'out', 'na')),
  motivo text,
  demo boolean not null default false,
  ejemplo boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, record_id)
);

alter table public.mediciones enable row level security;

drop policy if exists "Cada usuario puede leer sus mediciones" on public.mediciones;
create policy "Cada usuario puede leer sus mediciones"
  on public.mediciones for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Cada usuario puede guardar sus mediciones" on public.mediciones;
create policy "Cada usuario puede guardar sus mediciones"
  on public.mediciones for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Cada usuario puede borrar sus mediciones" on public.mediciones;
create policy "Cada usuario puede borrar sus mediciones"
  on public.mediciones for delete to authenticated
  using (auth.uid() = user_id);
